@TestSuiteMetadata(
    area="storage",
    category="functional",
    description="""
    Validates that hot-added data disks are usable by the LVM stack.

    PASS/FAIL is determined by functional gates only: hot-add
    enumeration in lsblk, 'fdisk -l' listing, pvcreate on all new
    devices, and a post-pvcreate lsblk check that no device is missing
    or reports size 0. NVMe 'Identify ... failed' messages found in
    dmesg are logged (not asserted) because some guests recover via
    kernel retry and complete the workload anyway.
    """,
    owner="rabdulfaizy",
    maturity="preview",
)
class LvmHotAddSuite(TestSuite):
    _DATA_DISK_SIZE_IN_GB = 10
    _DEFAULT_TIMEOUT = 3600
    # Time budget for polling lsblk after a hot-add: udev and the NVMe
    # rescan can lag behind the hot-add ARM operation by tens of seconds
    # on larger bursts. 60 sec has been enough for D8ds_v6 with 24 disks;
    # bump this if larger VM sizes / disk counts prove flaky.
    _HOT_ADD_LSBLK_POLL_TIMEOUT = 60
    # Poll cadence for the lsblk wait. Small enough that a fast hot-add
    # returns promptly, large enough not to hammer the SUT with SSH
    # invocations while udev is settling.
    _HOT_ADD_LSBLK_POLL_INTERVAL = 2

    # Match any Identify-family failure surfaced by the guest NVMe driver
    # so we can log bad-status returns from the NVMe controller, e.g.:
    #   nvme nvme1: Identify NS List failed (status=0xb)
    _NVME_IDENTIFY_FAIL_REGEX = re.compile(
        r"nvme\s+(?P<ctrl>nvme\d+):\s+Identify[^\n]*?failed\s+"
        r"\(status=(?P<status>0x[0-9a-fA-F]+)\)"
    )
    # NVMe status codes worth calling out separately in the log because
    # they indicate the controller returned an invalid response to a
    # spec-compliant Identify command (NVMe 1.4 sec 4.6.1 / 5.14.1.10):
    #   0xb  - Invalid Namespace or Format
    #   0x2  - Invalid Field in Command
    #   0xa  - Invalid Format
    _NVME_TRACKED_STATUS_CODES: Set[str] = {"0xb", "0x2", "0xa"}

    @TestCaseMetadata(
        description="""
        Hot-adds ALL remaining standard SSD data disks in a single call
        up to the VM's max_data_disk_count, then runs 'fdisk -l' /
        'pvcreate' on all newly attached devices and re-runs lsblk to
        confirm the devices remain usable. Also scans dmesg for NVMe
        'Identify ... failed' messages (informational only; does not
        fail the test).

        Steps:
        1. Snapshot lsblk output.
        2. Hot-add all remaining data disks in one call and verify they
           appear in lsblk with the expected size.
        3. Run 'fdisk -l' and confirm exit code 0.
        4. Run 'pvcreate' on ALL newly attached devices in a single
           bulk command so LVM opens every device in one syscall burst.
        5. Re-run lsblk and confirm each device still reports the
           expected size (did not collapse to 0B).
        6. Scan dmesg for 'nvme nvmeN: Identify ... failed (status=...)'
           and log an info line if any are found. PASS/FAIL is decided
           by steps 1-5 only.

        Parallel mode stresses udev: the burst of NS-Changed AENs after
        a bulk attach can cause pvcreate to open devices before udev has
        finished populating /sys/. The bulk pvcreate call amplifies that
        pressure by opening every device in one syscall.

        This test is generated by the lisa_test_writer prompt.
        """,
        priority=1,
        timeout=_DEFAULT_TIMEOUT,
        requirement=simple_requirement(
            supported_platform_type=[AZURE],
            unsupported_os=[BSD, Windows],
            disk=DiskStandardSSDLRS(
                # Require SKU capability, not a pre-attached disk. Using
                # 'data_disk_count' here forces LISA to attach N placeholder
                # disks at deploy time and burns LUN 0..N-1, so the test can
                # only hot-add max_data_disk_count - N devices (odd counts,
                # smaller burst). 'max_data_disk_count' filters at capability
                # level so ALL LUNs remain free for the hot-add burst.
                max_data_disk_count=search_space.IntRange(min=1),
            ),
        ),
        tags=["ai-generated"],
    )
    def verify_hot_add_disks_pvcreate_parallel_standard_ssd(
        self, node: Node, log: Logger, variables: Dict[str, Any]
    ) -> None:
        self._verify_hot_add_and_pvcreate(
            node=node,
            log=log,
            parallel=True,
            disk_type=schema.DiskType.StandardSSDLRS,
            variables=variables,
        )

