import re
from collections import Counter
from typing import List

from assertpy import assert_that
from microsoft.testsuites.performance.common import perf_nvme

from lisa import (
    Logger,
    Node,
    SkippedException,
    TestCaseMetadata,
    TestSuite,
    TestSuiteMetadata,
    simple_requirement,
)
from lisa.features import Nvme
from lisa.testsuite import TestResult
from lisa.tools import Dmesg, Fio, Hwclock, Lscpu
from lisa.tools.fio import IoEngine
from lisa.tools.kernel_config import KernelConfig


@TestSuiteMetadata(
    area="nvme",
    category="performance",
    description="""
    This test suite validates NVMe disk performance of Linux VMs using fio.
    """,
)
class NvmePerformace(TestSuite):
    TIME_OUT = 7200
    RTC_WRITE_ITERATIONS = 800
    _STALL_PATTERNS = [
        re.compile(pattern, re.IGNORECASE)
        for pattern in [
            r"BUG: soft lockup",
            r"rcu.*stall",
            r"blocked for more than",
            r"nvme.*(?:timeout|timed out|reset|not ready)",
            r"CSTS\s*=\s*0x[0-9a-f]+",
            r"hv_compose_msi_msg",
            r"nvme_reset_work",
        ]
    ]

    @TestCaseMetadata(
        description="""
        This test case uses fio to test NVMe disk performance
        using 'libaio' as ioengine
        """,
        priority=3,
        timeout=TIME_OUT,
        requirement=simple_requirement(
            supported_features=[Nvme],
        ),
    )
    def perf_nvme(self, node: Node, result: TestResult) -> None:
        perf_nvme(node, result)

    @TestCaseMetadata(
        description="""
        This test case uses fio to test NVMe disk performance
        using 'io_uring' as ioengine.
        """,
        priority=3,
        timeout=TIME_OUT,
        requirement=simple_requirement(
            supported_features=[Nvme],
        ),
    )
    def perf_nvme_io_uring(self, node: Node, result: TestResult) -> None:
        # Check if io_uring is available in kernel configuration
        kernel_config = node.tools[KernelConfig]
        if not kernel_config.is_enabled("CONFIG_IO_URING"):
            raise SkippedException("io_uring is not available in kernel configuration")
        perf_nvme(
            node,
            ioengine=IoEngine.IO_URING,
            result=result,
            max_iodepth=1024,
        )

    @TestCaseMetadata(
        description=(
            "This test case repeatedly writes system time to the hardware clock "
            "while running NVMe I/O, and verifies that the guest does not report "
            "CPU stalls or NVMe timeouts.\n"
            "This test is generated by the lisa_test_writer prompt."
        ),
        priority=3,
        timeout=TIME_OUT,
        requirement=simple_requirement(
            supported_features=[Nvme],
        ),
        tags=["ai-generated"],
    )
    def perf_nvme_rtc_stress(self, node: Node, log: Logger) -> None:
        nvme_namespaces = node.features[Nvme].get_raw_nvme_disks()
        assert_that(nvme_namespaces).described_as(
            "At least one NVMe namespace is required for RTC stress testing."
        ).is_not_empty()

        dmesg = node.tools[Dmesg]
        baseline_errors = Counter(
            self._get_stall_errors(dmesg.get_output(force_run=True))
        )
        fio_process = node.tools[Fio].launch_async(
            name="rtc_stress",
            filename=":".join(nvme_namespaces),
            mode="randread",
            iodepth=256,
            numjob=min(node.tools[Lscpu].get_core_count(), 64),
            time=self.TIME_OUT,
            time_based=True,
        )
        hwclock = node.tools[Hwclock]
        node.mark_dirty()

        try:
            for iteration in range(1, self.RTC_WRITE_ITERATIONS + 1):
                hwclock.set_rtc_clock_to_system_time()
                assert_that(fio_process.is_running()).described_as(
                    "NVMe workload stopped while writing the RTC on iteration "
                    f"{iteration}."
                ).is_true()
                if iteration % 100 == 0:
                    log.info(
                        f"completed {iteration} of "
                        f"{self.RTC_WRITE_ITERATIONS} RTC writes"
                    )
        finally:
            fio_process.kill()

        new_errors = (
            Counter(self._get_stall_errors(dmesg.get_output(force_run=True)))
            - baseline_errors
        )
        assert_that(sorted(new_errors.elements())).described_as(
            "RTC writes under NVMe load introduced CPU stalls or NVMe errors."
        ).is_empty()

    @classmethod
    def _get_stall_errors(cls, dmesg_output: str) -> List[str]:
        return [
            line
            for line in dmesg_output.splitlines()
            if any(pattern.search(line) for pattern in cls._STALL_PATTERNS)
        ]
