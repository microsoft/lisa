import re
from typing import Any, Dict, List, Set

from assertpy import assert_that

from lisa import (
    LisaException,
    Logger,
    Node,
    SkippedException,
    TestCaseMetadata,
    TestSuite,
    TestSuiteMetadata,
    create_timer,
    simple_requirement,
)
from lisa.features import Nvme
from lisa.operating_system import BSD, Windows
from lisa.tools import Dmesg, Hwclock, Ls, Rm
from lisa.util.perf_timer import Timer

# Kernel messages that indicate the guest stopped making progress.
_GUEST_STALL_PATTERN = re.compile(
    r"nvme\S*:.*timeout"
    r"|blocked for more than \d+ seconds"
    r"|rcu_\w+ (self-)?detected stall"
    r"|BUG: soft lockup",
    re.IGNORECASE,
)

# util-linux hwclock messages when the RTC update interrupt never arrives.
_RTC_TICK_TIMEOUT_PATTERN = re.compile(
    r"timed out waiting for time change|wait for clock tick timed out",
    re.IGNORECASE,
)

# Hyper-V integration service devices that keep signaling a healthy guest.
_VMBUS_IC_DEVICES = {
    "57164f39-9115-4e78-ab55-382f3bd5422d": "Heartbeat",
    "9527e630-d0ae-497b-adce-e80ab0175caf": "Time Synchronization",
}

# Minimum observation window before channel interrupt counters are compared.
_VMBUS_MIN_WINDOW_SECONDS = 120

_OS_DISK_PROBE_FILE = "/var/tmp/lisa_rtc_stress_probe"
_PROBE_TIMEOUT_SECONDS = 120


@TestSuiteMetadata(
    area="time",
    category="stress",
    description="""
    This test suite stresses RTC (CMOS clock) synchronization and verifies the
    guest stays responsive.
    """,
)
class RtcStress(TestSuite):
    @TestCaseMetadata(
        description="""
        Linux periodically writes system time to the RTC (the kernel's
        11-minute RTC sync mode, or 'hwclock --systohc'). This test performs
        many RTC writes in a short time, as a long-running VM would over days,
        and verifies that the RTC keeps working and the guest stays responsive.

        Steps:
        1. Skip if there is no /dev/rtc0.
        2. Write system time to the RTC 'rtc_write_count' times (default 1000),
           'rtc_write_interval' seconds apart (default 2).
        3. After every 'rtc_probe_every' writes (default 50), verify:
           a. 'hwclock --show' completes and gets an RTC update interrupt.
           b. VMBus integration service channels (Heartbeat, Time
              Synchronization) that showed activity in the first window keep
              receiving interrupts.
           c. An O_DIRECT write to the OS disk completes, and an O_DIRECT read
              of every local NVMe namespace (if any) completes.
        4. Fail if any check fails or times out, or if new hung task, RCU
           stall, soft lockup or NVMe timeout messages appear in dmesg.

        This test is generated by the lisa_test_writer prompt.
        """,
        priority=2,
        timeout=7200,
        requirement=simple_requirement(
            unsupported_os=[BSD, Windows],
        ),
        tags=["ai-generated"],
    )
    def verify_rtc_write_stress_test(
        self, node: Node, log: Logger, variables: Dict[str, Any]
    ) -> None:
        # --- Arrange ---
        write_count = _get_int_variable(variables, "rtc_write_count", 1000)
        interval = _get_int_variable(
            variables, "rtc_write_interval", 2, allow_zero=True
        )
        probe_every = _get_int_variable(variables, "rtc_probe_every", 50)

        if not node.tools[Ls].path_exists("/dev/rtc0", sudo=True):
            raise SkippedException("/dev/rtc0 is not present on this guest.")
        hwclock = node.tools[Hwclock]

        nvme_namespaces: List[str] = []
        if node.features.is_supported(Nvme):
            nvme_namespaces = node.features[Nvme].get_raw_nvme_disks()
        log.info(f"Local NVMe namespaces to probe: {nvme_namespaces or 'none'}")

        channel_dirs = self._get_ic_channel_dirs(node)
        log.info(f"VMBus integration service channels to monitor: {channel_dirs}")

        dmesg = node.tools[Dmesg]
        baseline_dmesg: Set[str] = set(dmesg.get_output(force_run=True).splitlines())
        self._check_rtc_tick(hwclock, writes_done=0)
        self._probe_io(node, nvme_namespaces, writes_done=0)

        # A failing run can leave the guest unresponsive; do not reuse it.
        node.mark_dirty()

        # --- Act ---
        log.info(
            f"Writing RTC {write_count} times, {interval}s apart, checking guest "
            f"liveness every {probe_every} writes."
        )
        window_timer = create_timer()
        window_start = self._read_channel_interrupts(node, channel_dirs)
        live_channels: List[str] = []
        calibrated = False
        writes_done = 0
        while writes_done < write_count:
            batch = min(probe_every, write_count - writes_done)
            self._write_rtc_batch(node, hwclock.command, batch, interval, writes_done)
            writes_done += batch

            self._check_rtc_tick(hwclock, writes_done)
            self._probe_io(node, nvme_namespaces, writes_done)
            if window_timer.elapsed(False) >= _VMBUS_MIN_WINDOW_SECONDS:
                window_end = self._read_channel_interrupts(node, channel_dirs)
                if not calibrated:
                    # Only channels active at the start are asserted, so idle
                    # channels don't cause false failures.
                    live_channels = [
                        c for c in channel_dirs if window_end[c] > window_start[c]
                    ]
                    calibrated = True
                    log.info(f"VMBus channels active: {live_channels}")
                else:
                    self._assert_channels_progressed(
                        live_channels, window_start, window_end, window_timer
                    )
                window_start = window_end
                window_timer = create_timer()
            log.info(f"{writes_done}/{write_count} RTC writes, guest healthy.")

        # --- Assert ---
        new_stall_lines = [
            line
            for line in dmesg.get_output(force_run=True).splitlines()
            if line not in baseline_dmesg and _GUEST_STALL_PATTERN.search(line)
        ]
        assert_that(new_stall_lines).described_as(
            f"Guest stall messages appeared in dmesg after {write_count} RTC " "writes."
        ).is_empty()
        if not live_channels:
            log.info(
                "No VMBus integration service channel showed activity in the "
                f"first {_VMBUS_MIN_WINDOW_SECONDS}s window, so channel "
                "activity was not asserted."
            )

    def after_case(self, log: Logger, **kwargs: Any) -> None:
        """
        Remove the OS disk probe file.
        """
        node: Node = kwargs["node"]
        node.tools[Rm].remove_file(_OS_DISK_PROBE_FILE, sudo=True)

    def _write_rtc_batch(
        self,
        node: Node,
        hwclock_cmd: str,
        count: int,
        interval: int,
        writes_done: int,
    ) -> None:
        # Pace the writes on the guest to avoid one SSH round trip per write.
        # 'hwclock --systohc' uses RTC_SET_TIME on /dev/rtc0, the same rtc_cmos
        # path the kernel's 11-minute sync mode uses.
        cmd = (
            f"for i in $(seq 1 {count}); do "
            f"{hwclock_cmd} --systohc || exit 1; sleep {interval}; done"
        )
        # hwclock waits up to ~1s for the next second boundary on each write.
        timeout = count * (interval + 5) + 60
        result = node.execute(cmd, shell=True, sudo=True, timeout=timeout)
        assert_that(result.exit_code).described_as(
            f"RTC write failed in writes {writes_done + 1}-{writes_done + count}. "
            f"Output: {result.stdout} {result.stderr}".strip()
        ).is_equal_to(0)

    def _check_rtc_tick(self, hwclock: Hwclock, writes_done: int) -> None:
        # 'hwclock --show' waits for the RTC update interrupt (clock tick).
        try:
            result = hwclock.run(
                "--show --verbose",
                sudo=True,
                force_run=True,
                timeout=_PROBE_TIMEOUT_SECONDS,
            )
        except LisaException as e:
            raise LisaException(
                f"RTC read did not complete after {writes_done} RTC writes. "
                f"Original error: {e}"
            ) from e
        output = f"{result.stdout}\n{result.stderr}".strip()
        assert_that(_RTC_TICK_TIMEOUT_PATTERN.search(output)).described_as(
            f"RTC update interrupt did not arrive after {writes_done} RTC "
            f"writes. hwclock output: {output}"
        ).is_none()
        assert_that(result.exit_code).described_as(
            f"RTC read failed after {writes_done} RTC writes. "
            f"hwclock output: {output}"
        ).is_equal_to(0)

    def _probe_io(
        self, node: Node, nvme_namespaces: List[str], writes_done: int
    ) -> None:
        probes = {
            "OS disk": (
                f"dd if=/dev/zero of={_OS_DISK_PROBE_FILE} bs=4k count=256 "
                "oflag=direct conv=fsync"
            )
        }
        for namespace in nvme_namespaces:
            probes[namespace] = (
                f"dd if={namespace} of=/dev/null bs=4k count=256 iflag=direct"
            )
        for target, cmd in probes.items():
            try:
                result = node.execute(
                    cmd,
                    shell=True,
                    sudo=True,
                    timeout=_PROBE_TIMEOUT_SECONDS,
                )
            except LisaException as e:
                raise LisaException(
                    f"I/O on {target} did not complete after {writes_done} RTC "
                    "writes. Guest I/O stopped making progress. "
                    f"Original error: {e}"
                ) from e
            assert_that(result.exit_code).described_as(
                f"I/O on {target} failed after {writes_done} RTC writes. "
                f"Output: {result.stdout} {result.stderr}".strip()
            ).is_equal_to(0)

    def _get_ic_channel_dirs(self, node: Node) -> List[str]:
        ls = node.tools[Ls]
        channel_dirs: List[str] = []
        for class_id in _VMBUS_IC_DEVICES:
            result = node.execute(
                f"grep -l -i '{class_id}' /sys/bus/vmbus/devices/*/class_id",
                shell=True,
                sudo=True,
            )
            # grep exits 1 when the device is not present.
            if result.exit_code not in (0, 1):
                raise LisaException(
                    f"failed to look up VMBus class {class_id}: {result.stderr}"
                )
            for class_id_file in result.stdout.splitlines():
                device_dir = class_id_file.rsplit("/", 1)[0]
                channel_dirs.extend(ls.list_dir(f"{device_dir}/channels", sudo=True))
        return [c.rstrip("/") for c in channel_dirs]

    def _read_channel_interrupts(
        self, node: Node, channel_dirs: List[str]
    ) -> Dict[str, int]:
        counters: Dict[str, int] = {}
        for channel_dir in channel_dirs:
            # 'interrupts' counts interrupts received on the channel.
            value = node.execute(
                f"cat {channel_dir}/interrupts",
                sudo=True,
                expected_exit_code=0,
                expected_exit_code_failure_message=(
                    f"failed to read {channel_dir}/interrupts"
                ),
            ).stdout.strip()
            if not value.isdigit():
                raise LisaException(
                    f"unexpected value in {channel_dir}/interrupts: '{value}'"
                )
            counters[channel_dir] = int(value)
        return counters

    def _assert_channels_progressed(
        self,
        live_channels: List[str],
        window_start: Dict[str, int],
        window_end: Dict[str, int],
        window_timer: Timer,
    ) -> None:
        stalled = [c for c in live_channels if window_end[c] <= window_start[c]]
        assert_that(stalled).described_as(
            "VMBus integration service channels received no interrupts for "
            f"{window_timer.elapsed(False):.0f}s during RTC write stress."
        ).is_empty()


def _get_int_variable(
    variables: Dict[str, Any], name: str, default: int, allow_zero: bool = False
) -> int:
    raw_value = variables.get(name, default)
    try:
        value = int(raw_value)
    except (TypeError, ValueError) as e:
        raise LisaException(
            f"variable '{name}' must be an integer, got '{raw_value}'"
        ) from e
    minimum = 0 if allow_zero else 1
    if value < minimum:
        raise LisaException(f"variable '{name}' must be >= {minimum}, got {value}")
    return value
