from assertpy import assert_that

from lisa import (
    Node,
    TestCaseMetadata,
    TestSuite,
    TestSuiteMetadata,
    simple_requirement,
)
from lisa.operating_system import Windows


@TestSuiteMetadata(
    area="core",
    category="functional",
    description="Validates direct command execution on Windows.",
    owner="Microsoft",
)
class WindowsExecute(TestSuite):
    """Demonstrate node.execute without a Tool wrapper on Windows."""

    @TestCaseMetadata(
        description=(
            "Run a native executable, explicitly invoke PowerShell, and verify "
            "separate stdout/stderr and a nonzero exit code from cmd.exe.\n"
            "This test is generated by the lisa_test_writer prompt."
        ),
        priority=1,
        timeout=180,
        requirement=simple_requirement(supported_os=[Windows]),
        tags=["ai-generated"],
    )
    def verify_node_execute_on_windows(self, node: Node) -> None:
        identity = node.execute("whoami.exe", timeout=30, expected_exit_code=0)
        assert_that(identity.stdout.strip()).described_as(
            f"whoami.exe should return the current identity; stderr: {identity.stderr}"
        ).is_not_empty()

        platform = node.execute(
            "powershell.exe -NoProfile -NonInteractive -Command "
            "[Environment]::OSVersion.Platform.ToString()",
            timeout=30,
            expected_exit_code=0,
        )
        assert_that(platform.stdout.strip()).described_as(
            f"PowerShell should identify Windows; stderr: {platform.stderr}"
        ).is_equal_to("Win32NT")

        streams = node.execute(
            "echo LISA_STDOUT & echo LISA_STDERR 1>&2 & exit /b 7",
            shell=True,
            no_error_log=True,
            timeout=30,
            expected_exit_code=7,
        )
        assert_that(streams.stdout.strip()).described_as(
            "cmd.exe stdout should be captured separately"
        ).is_equal_to("LISA_STDOUT")
        assert_that(streams.stderr.strip()).described_as(
            "cmd.exe stderr should be captured separately"
        ).is_equal_to("LISA_STDERR")
