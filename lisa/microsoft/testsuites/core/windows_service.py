from pathlib import Path, PurePath
from uuid import uuid4

from assertpy import assert_that

from lisa import (
    Logger,
    Node,
    TestCaseMetadata,
    TestSuite,
    TestSuiteMetadata,
    simple_requirement,
)
from lisa.base_tools.service import WindowsService
from lisa.operating_system import Windows
from lisa.tools import PowerShell
from lisa.util import LisaException, check_till_timeout


@TestSuiteMetadata(
    area="core",
    category="functional",
    description="Validates automatic recovery of Windows background services.",
)
class WindowsServiceRecovery(TestSuite):
    """Exercise SCM recovery using an isolated service, never a system service."""

    @TestCaseMetadata(
        description=(
            "Verify that Service Control Manager automatically restarts a crashed "
            "service and that its new process resumes producing heartbeats.\n"
            "This test is generated by the lisa_test_writer prompt."
        ),
        priority=1,
        timeout=600,
        requirement=simple_requirement(supported_os=[Windows]),
        tags=["ai-generated"],
    )
    def verify_windows_service_failure_recovery(self, node: Node, log: Logger) -> None:
        service = node.tools[WindowsService]
        powershell = node.tools[PowerShell]
        name = f"LisaRecovery{uuid4().hex}"
        directory = node.working_path / f"service recovery {uuid4().hex}"
        executable = directory / "recovery_service.exe"
        heartbeat = directory / "heartbeat.txt"
        source = directory / "recovery_service.cs"
        directory_literal = self._literal(directory)
        executable_literal = self._literal(executable)
        heartbeat_literal = self._literal(heartbeat)
        source_literal = self._literal(source)
        if service.check_service_exists(name):
            raise LisaException(f"Refusing to reuse existing service '{name}'")
        powershell.run_cmdlet(
            f"New-Item -ItemType Directory -Path {directory_literal} -ErrorAction Stop",
            force_run=True,
        )
        try:
            node.shell.copy(
                Path(__file__).parent / "test_data" / "recovery_service.cs", source
            )
            powershell.run_cmdlet(
                "$ErrorActionPreference = 'Stop'; "
                f"Add-Type -Path {source_literal} "
                "-ReferencedAssemblies System.ServiceProcess.dll,System.dll "
                f"-OutputAssembly {executable_literal} -OutputType WindowsApplication; "
                f'$binary = \'"\' + {executable_literal} + \'" "{name}" "\' + '
                f"{heartbeat_literal} + '\"'; "
                f"New-Service -Name '{name}' -BinaryPathName $binary "
                "-StartupType Manual",
                force_run=True,
                timeout=120,
            )
            service.configure_failure_restart(name, restart_delay_ms=1000)
            service.start_service(name)
            original_pid = service.get_process_id(name)
            assert_that(original_pid).is_greater_than(0)
            check_till_timeout(
                lambda: self._has_heartbeat(powershell, heartbeat, original_pid),
                "The original service process did not produce heartbeats",
                timeout=60,
            )
            log.info(f"Crashing owned service '{name}' with PID {original_pid}")
            powershell.run_cmdlet(
                "$ErrorActionPreference = 'Stop'; "
                f"$service = Get-CimInstance Win32_Service -Filter \"Name='{name}'\"; "
                f"if ($service.ProcessId -ne {original_pid}) "
                "{ throw 'Service PID changed before fault injection' }; "
                f"$process = Get-Process -Id {original_pid}; "
                f"if ($process.Path -ne {executable_literal}) "
                "{ throw 'Refusing to terminate an unexpected executable' }; "
                f"Stop-Process -Id {original_pid} -Force -ErrorAction Stop",
                force_run=True,
            )

            def recovered() -> bool:
                if not service.is_service_running(name):
                    return False
                current_pid = service.get_process_id(name)
                return (
                    current_pid > 0
                    and current_pid != original_pid
                    and self._has_heartbeat(powershell, heartbeat, current_pid)
                )

            check_till_timeout(
                recovered,
                "SCM did not restart the crashed service with a new working process",
                timeout=120,
            )
            log.info(
                f"Service '{name}' recovered automatically: "
                f"PID {original_pid} -> {service.get_process_id(name)}; "
                "new process produced multiple heartbeats"
            )
        finally:
            try:
                self._cleanup(node, service, name, directory, executable)
            except LisaException:
                node.mark_dirty()
                raise

    @staticmethod
    def _literal(path: PurePath) -> str:
        return "'" + str(path).replace("'", "''") + "'"

    def _has_heartbeat(
        self, powershell: PowerShell, path: PurePath, process_id: int
    ) -> bool:
        literal = self._literal(path)
        output = str(
            powershell.run_cmdlet(
                "$ErrorActionPreference = 'Stop'; "
                f"if (Test-Path -LiteralPath {literal}) {{ "
                f"Get-Content -LiteralPath {literal} | "
                "Where-Object { $_ -match '^\\d+:\\d+$' } | Select-Object -Last 1 }",
                force_run=True,
            )
        ).strip()
        if not output:
            return False
        pid_text, sequence_text = output.split(":")
        return int(pid_text) == process_id and int(sequence_text) >= 2

    def _cleanup(
        self,
        node: Node,
        service: WindowsService,
        name: str,
        directory: PurePath,
        executable: PurePath,
    ) -> None:
        powershell = node.tools[PowerShell]
        if service.check_service_exists(name):
            powershell.run_cmdlet(
                "$ErrorActionPreference = 'Stop'; "
                f"$service = Get-CimInstance Win32_Service -Filter \"Name='{name}'\"; "
                f"if (-not $service.PathName.StartsWith('\"' + "
                f"{self._literal(executable)} + '\"')) "
                "{ throw 'Refusing to clean up an unexpected service' }",
                force_run=True,
            )
            service.stop_service(name)
            powershell.run_cmdlet(
                f"& \"$env:SystemRoot\\System32\\sc.exe\" delete '{name}'; "
                "if ($LASTEXITCODE -ne 0) { "
                'throw "Failed to delete test service: $LASTEXITCODE" }',
                force_run=True,
            )
            check_till_timeout(
                lambda: not service.check_service_exists(name),
                f"Test service '{name}' was not deleted",
                timeout=60,
            )
        directory_literal = self._literal(directory)
        powershell.run_cmdlet(
            "$ErrorActionPreference = 'Stop'; "
            f"Remove-Item -LiteralPath {directory_literal} -Recurse -Force; "
            f"if (Test-Path -LiteralPath {directory_literal}) "
            "{ throw 'Test service directory was not removed' }",
            force_run=True,
        )
